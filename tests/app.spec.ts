test('component 2: two-axis map places cards by hand, edits axes and saves per board', async ({ page }) => {
    await page.goto('/');
    await expect(page.locator('.react-flow')).toBeVisible();
    await page.getByRole('radio', { name: '二軸四象限マップ' }).click();
    const plane = page.getByRole('group', { name: /^二軸四象限マップ。/ });
    await expect(plane).toBeVisible();
    await expect(page.locator('.quad-tray .quad-chip')).toHaveCount(6);
    const box = (await plane.boundingBox())!;
    const chip = page.locator('.quad-tray .quad-chip').first();
    const cb = (await chip.boundingBox())!;
    await page.mouse.move(cb.x + 12, cb.y + cb.height / 2);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width * 0.8, box.y + box.height * 0.2, { steps: 8 });
    await page.mouse.up();
    await expect(plane.locator('.quad-chip')).toHaveCount(1);
    await expect(plane.locator('.quad-chip')).toHaveAccessibleName(/すぐ試す/);
    await page.locator('.quad-tray .quad-chip').first().focus();
    await page.keyboard.press('Enter');
    await expect(plane.locator('.quad-chip')).toHaveCount(2);
    await page.getByRole('textbox', { name: '横軸の右' }).fill('前例がない');
    await page.getByRole('textbox', { name: '横軸の右' }).press('Enter');
    await expect(page.getByText('前例がない ▶')).toBeVisible();
    await expect(page.getByRole('combobox', { name: '軸のセット' })).toHaveValue('custom');
    await page.getByRole('button', { name: '空白：ここを狙う付箋を置く' }).first().click();
    await expect(plane.locator('.quad-chip')).toHaveCount(3);
    const placed = plane.locator('.quad-chip').first();
    await placed.focus();
    await page.keyboard.press('Delete');
    await expect(plane.locator('.quad-chip')).toHaveCount(2);
    await page.waitForTimeout(500);
    await page.reload();
    await page.getByRole('radio', { name: '二軸四象限マップ' }).click();
    await expect(page.getByRole('group', { name: /^二軸四象限マップ。/ }).locator('.quad-chip')).toHaveCount(2);
    await page.getByRole('radio', { name: 'ホワイトボード' }).click();
    await expect(page.locator('.react-flow__node')).toHaveCount(7);
});
