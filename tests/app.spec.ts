test('theme switch applies dark/light/auto and survives a reload', async ({ page }) => {
    const errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('/');
    await expect(page.locator('.react-flow')).toBeVisible();
    const html = page.locator('html');
    await expect(html).not.toHaveAttribute('data-theme', /.+/);
    await page.getByRole('radio', { name: 'ダーク' }).click();
    await expect(html).toHaveAttribute('data-theme', 'dark');
    await expect(page.locator('.react-flow')).toHaveClass(/dark/);
    await page.reload();
    await expect(page.locator('.react-flow')).toBeVisible();
    await expect(html).toHaveAttribute('data-theme', 'dark');
    await page.getByRole('radio', { name: 'ライト' }).click();
    await expect(html).toHaveAttribute('data-theme', 'light');
    await page.getByRole('radio', { name: '自動（OSに合わせる）' }).click();
    await expect(html).not.toHaveAttribute('data-theme', /.+/);
    expect(await page.evaluate(() => localStorage.getItem('game-brainstormer.theme'))).toBeNull();
    expect(errors).toEqual([]);
});
